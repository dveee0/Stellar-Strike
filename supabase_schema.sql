-- ========================================================
-- STELLAR STRIKE: LEADERBOARD TABLE SCHEMA FOR SUPABASE
-- Skrip ini sepenuhnya idempotent (aman dijalankan berulang kali)
-- ========================================================

-- 1. Buat Tabel Leaderboard
create table if not exists leaderboard (
  id bigint generated by default as identity primary key,
  player_name varchar(32) not null,
  score bigint not null,
  wave integer not null default 1,
  wpm integer not null default 0,
  accuracy integer not null default 100,
  rank_title varchar(64) default 'Kadet Antariksa',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Buat Index untuk performa query Top Scores
create index if not exists idx_leaderboard_score on leaderboard (score desc);
create index if not exists idx_leaderboard_created_at on leaderboard (created_at desc);

-- 3. Aktifkan Row Level Security (RLS)
alter table leaderboard enable row level security;

-- 4. Kebijakan Public Read (Drop dulu jika sudah ada agar tidak error 42710)
drop policy if exists "Allow public read access" on leaderboard;
create policy "Allow public read access"
  on leaderboard
  for select
  using (true);

-- 5. Kebijakan Public Insert (Drop dulu jika sudah ada agar tidak error 42710)
drop policy if exists "Allow public insert access" on leaderboard;
create policy "Allow public insert access"
  on leaderboard
  for insert
  with check (
    length(player_name) > 0 and
    length(player_name) <= 32 and
    score >= 0 and
    wave >= 1
  );

-- 6. Reload schema cache Supabase secara instan
notify pgrst, 'reload schema';
